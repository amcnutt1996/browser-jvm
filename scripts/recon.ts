// Scans a jar and writes a Markdown report of what it needs from the JDK.
// Usage: node scripts/recon.ts <jar> <out.md>
import { readFileSync, writeFileSync } from "node:fs";
import {
  ACC_NATIVE,
  ACC_SYNCHRONIZED,
  CONSTANT_Class,
  CONSTANT_Fieldref,
  CONSTANT_InterfaceMethodref,
  CONSTANT_InvokeDynamic,
  CONSTANT_MethodHandle,
  CONSTANT_Methodref,
  type ClassFile,
  parseClassFile,
} from "../src/jvm/classfile.ts";
import { forEachInstruction } from "../src/jvm/opcodes.ts";
import { ZipArchive } from "../src/jvm/zip.ts";

const [jarPath, outPath] = process.argv.slice(2);
const zip = new ZipArchive(readFileSync(jarPath));
const classes = new Map<string, ClassFile>();

for (const name of zip.entries.keys()) {
  if (!name.endsWith(".class") || name.startsWith("META-INF/")) continue;
  const cf = parseClassFile(zip.read(name)!);
  classes.set(cf.name, cf);
}

const isJdk = (name: string): boolean =>
  /^(?:java|javax|sun|jdk|com\/sun)\//.test(name);
const typesIn = (descriptor: string): string[] =>
  [...descriptor.matchAll(/L([^;]+);/g)].map((m) => m[1]);
const elementClass = (name: string): string | undefined => {
  if (!name.startsWith("[")) return name;
  const types = typesIn(name);
  return types[0];
};
const pkgOf = (name: string): string => name.slice(0, name.lastIndexOf("/"));
const group = (name: string): string => {
  const parts = name.split("/");
  const depth = parts[0] === "com" || parts[0] === "org" ? 3 : 2;
  return parts.slice(0, Math.min(depth, parts.length - 1)).join("/");
};

const refsOf = (cf: ClassFile): Set<string> => {
  const refs = new Set<string>();
  const add = (n: string | undefined): void => {
    const c = n && elementClass(n);
    if (c) refs.add(c);
  };
  add(cf.superName);
  cf.interfaces.forEach(add);
  for (const e of cf.constantPool) {
    if (!e) continue;
    if (e.tag === CONSTANT_Class) add(e.value);
    else if (
      e.tag === CONSTANT_Fieldref ||
      e.tag === CONSTANT_Methodref ||
      e.tag === CONSTANT_InterfaceMethodref
    ) {
      add(e.value.className);
      typesIn(e.value.descriptor).forEach(add);
    } else if (e.tag === CONSTANT_InvokeDynamic) {
      typesIn(e.value.descriptor).forEach(add);
    }
  }
  for (const f of cf.fields) typesIn(f.descriptor).forEach(add);
  for (const m of cf.methods) typesIn(m.descriptor).forEach(add);
  return refs;
};

const MAIN = "com/shatteredpixel/shatteredpixeldungeon/desktop/DesktopLauncher";
const reachable = (exclude: (n: string) => boolean): Set<string> => {
  const seen = new Set<string>();
  const queue = [MAIN];
  while (queue.length) {
    const n = queue.pop()!;
    if (seen.has(n)) continue;
    seen.add(n);
    const cf = classes.get(n);
    if (!cf || exclude(n)) continue;
    for (const r of refsOf(cf)) if (!seen.has(r)) queue.push(r);
  }
  return seen;
};
const BACKEND = /^(?:com\/badlogic\/gdx\/backends\/lwjgl3\/|org\/lwjgl\/|com\/studiohartman\/)/;
const reachAll = reachable(() => false);
const reachGame = reachable((n) => BACKEND.test(n));

const out: string[] = [];
const line = (s = ""): void => {
  out.push(s);
};
const table = (head: string[], rows: (string | number)[][]): void => {
  line(`| ${head.join(" | ")} |`);
  line(`| ${head.map(() => "---").join(" | ")} |`);
  for (const r of rows) line(`| ${r.join(" | ")} |`);
  line();
};
const sortCount = <T>(m: Map<T, number>): [T, number][] =>
  [...m].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));
const inc = <T>(m: Map<T, number>, k: T, n = 1): void => {
  m.set(k, (m.get(k) ?? 0) + n);
};

const versions = new Map<number, number>();
const byGroup = new Map<string, number>();
for (const cf of classes.values()) {
  inc(versions, cf.majorVersion);
  inc(byGroup, group(cf.name));
}

line("# Recon: Shattered Pixel Dungeon v4.0.2 desktop jar");
line();
line(
  "Generated by `scripts/javaRunner/recon.ts` from the official `ShatteredPD-v4.0.2-Java.jar` (sha256 `bcefd52a…ec602`)."
);
line();
line("## Overview");
line();
line(`- Entries in jar: ${zip.entries.size}`);
line(`- Class files (outside META-INF): ${classes.size}`);
line(
  `- Native library bytes (.so/.dll/.dylib): ${[...zip.entries.values()]
    .filter((e) => /\.(?:so|dll|dylib)$/.test(e.name))
    .reduce((a, e) => a + e.size, 0)
    .toLocaleString("en-US")}`
);
line(
  `- Classes reachable from \`DesktopLauncher\` (class-level, all references): ${[...reachAll].filter((n) => classes.has(n)).length}`
);
line(
  `- Same, but not following the LWJGL3 backend, LWJGL and Jamepad (the classes the runner replaces): ${[...reachGame].filter((n) => classes.has(n)).length}`
);
line(
  `- JDK classes referenced by the whole jar: ${new Set([...classes.values()].flatMap((cf) => [...refsOf(cf)].filter(isJdk))).size}; by the reachable game set: ${[...reachGame].filter(isJdk).length}`
);
line();
table(
  ["Class file major version", "Classes"],
  sortCount(versions).map(([v, c]) => [v, c])
);
table(["Package group", "Classes"], sortCount(byGroup));

// JDK class/method references
type Usage = { classes: Map<string, number>; members: Map<string, number> };
const usage = (filter: (cf: ClassFile) => boolean): Usage => {
  const u: Usage = { classes: new Map(), members: new Map() };
  for (const cf of classes.values()) {
    if (!filter(cf)) continue;
    for (const r of refsOf(cf)) if (isJdk(r)) inc(u.classes, r);
    for (const e of cf.constantPool) {
      if (
        e &&
        (e.tag === CONSTANT_Fieldref ||
          e.tag === CONSTANT_Methodref ||
          e.tag === CONSTANT_InterfaceMethodref) &&
        isJdk(e.value.className)
      ) {
        inc(u.members, `${e.value.className}.${e.value.name}${e.tag === CONSTANT_Fieldref ? ":" : ""}${e.value.descriptor}`);
      }
    }
  }
  return u;
};
const gameUsage = usage((cf) => reachGame.has(cf.name));
const allUsage = usage(() => true);

line("## JDK classes referenced");
line();
line(
  "Count = number of jar classes whose constant pool or signatures reference the JDK class. `game` = classes reachable from `DesktopLauncher` without the LWJGL3 backend; `all` = whole jar."
);
line();
const jdkByPkg = new Map<string, string[]>();
for (const n of allUsage.classes.keys()) {
  const p = pkgOf(n);
  jdkByPkg.set(p, [...(jdkByPkg.get(p) ?? []), n]);
}
for (const [p, names] of [...jdkByPkg].sort((a, b) => a[0].localeCompare(b[0]))) {
  line(`### \`${p.replaceAll("/", ".")}\``);
  line();
  table(
    ["Class", "game", "all"],
    names
      .sort((a, b) => (allUsage.classes.get(b) ?? 0) - (allUsage.classes.get(a) ?? 0) || a.localeCompare(b))
      .map((n) => [`\`${n.slice(p.length + 1)}\``, gameUsage.classes.get(n) ?? 0, allUsage.classes.get(n) ?? 0])
  );
}

line("## JDK methods and fields referenced");
line();
line("One row per distinct member reference (`Class.name descriptor`; fields marked with `:`). Counts are constant pool entries across classes.");
line();
const memberByClass = new Map<string, [string, number][]>();
for (const [m, c] of allUsage.members) {
  const cls = m.slice(0, m.indexOf("."));
  memberByClass.set(cls, [...(memberByClass.get(cls) ?? []), [m.slice(cls.length + 1), c]]);
}
for (const [cls, members] of [...memberByClass].sort((a, b) => a[0].localeCompare(b[0]))) {
  line(`<details><summary><code>${cls.replaceAll("/", ".")}</code> (${members.length})</summary>`);
  line();
  for (const [m, c] of members.sort((a, b) => a[0].localeCompare(b[0]))) {
    const g = gameUsage.members.get(`${cls}.${m}`) ?? 0;
    line(`- \`${m}\` (game ${g}, all ${c})`);
  }
  line();
  line("</details>");
  line();
}

// invokedynamic
const bsms = new Map<string, number>();
const lambdaTypes = new Map<string, number>();
const indyByVersion = new Map<string, number>();
for (const cf of classes.values()) {
  for (const e of cf.constantPool) {
    if (e?.tag !== CONSTANT_InvokeDynamic) continue;
    const bm = cf.bootstrapMethods[e.value.bootstrapIndex];
    const mh = cf.constantPool[bm.methodRef];
    if (mh?.tag !== CONSTANT_MethodHandle) continue;
    const key = `${mh.value.ref.className}.${mh.value.ref.name}`;
    inc(bsms, key);
    inc(indyByVersion, `${key} (class version ${cf.majorVersion})`);
    if (key.endsWith("LambdaMetafactory.metafactory") || key.endsWith("altMetafactory")) {
      const ret = e.value.descriptor.slice(e.value.descriptor.indexOf(")") + 1);
      inc(lambdaTypes, `${ret.slice(1, -1).replaceAll("/", ".")}.${e.value.name}`);
    }
  }
}
line("## invokedynamic bootstrap methods");
line();
table(["Bootstrap method", "Call sites"], sortCount(bsms).map(([k, v]) => [`\`${k}\``, v]));
table(["Bootstrap method by class version", "Call sites"], sortCount(indyByVersion).map(([k, v]) => [`\`${k}\``, v]));
line("Functional interfaces implemented by lambdas and method references:");
line();
table(["Interface.method", "Sites"], sortCount(lambdaTypes).map(([k, v]) => [`\`${k}\``, v]));

// natives
const natives = new Map<string, string[]>();
for (const cf of classes.values()) {
  for (const m of cf.methods) {
    if (m.access & ACC_NATIVE) {
      const g = group(cf.name);
      natives.set(g, [...(natives.get(g) ?? []), `${cf.name.replaceAll("/", ".")}.${m.name}${m.descriptor}`]);
    }
  }
}
line("## Native methods declared in the jar");
line();
table(
  ["Library (package group)", "Native methods", "Reachable from game set"],
  [...natives].sort((a, b) => b[1].length - a[1].length).map(([g, ms]) => [`\`${g}\``, ms.length, ms.filter((m) => reachGame.has(m.slice(0, m.lastIndexOf(".", m.indexOf("("))).replaceAll(".", "/"))).length])
);
for (const [g, ms] of [...natives].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (g.startsWith("org/lwjgl")) {
    const perClass = new Map<string, number>();
    for (const m of ms) inc(perClass, m.slice(0, m.lastIndexOf(".", m.indexOf("("))));
    line(`<details><summary><code>${g}</code>: ${ms.length} natives in ${perClass.size} classes (per class counts)</summary>`);
    line();
    for (const [c, n] of sortCount(perClass)) line(`- \`${c}\` ${n}`);
  } else {
    line(`<details><summary><code>${g}</code>: ${ms.length} natives</summary>`);
    line();
    for (const m of ms.sort()) line(`- \`${m}\``);
  }
  line();
  line("</details>");
  line();
}

// specific usages
const callers = (pattern: RegExp, filter: (cf: ClassFile) => boolean = () => true): Map<string, number> => {
  const m = new Map<string, number>();
  for (const cf of classes.values()) {
    if (!filter(cf)) continue;
    for (const e of cf.constantPool) {
      if (
        e &&
        (e.tag === CONSTANT_Methodref || e.tag === CONSTANT_InterfaceMethodref || e.tag === CONSTANT_Fieldref) &&
        pattern.test(`${e.value.className}.${e.value.name}`)
      ) {
        inc(m, `${group(cf.name)} → ${e.value.className.replaceAll("/", ".")}.${e.value.name}`);
      }
    }
  }
  return m;
};
const section = (title: string, pattern: RegExp, note?: string): void => {
  line(`### ${title}`);
  line();
  if (note) {
    line(note);
    line();
  }
  const m = callers(pattern);
  if (m.size === 0) {
    line("None.");
    line();
    return;
  }
  table(["Caller package → member", "Classes"], sortCount(m).map(([k, v]) => [`\`${k}\``, v]));
};

line("## Feature usage");
line();
section("Reflection: Class.forName, newInstance, members", /^java\/lang\/(?:Class\.(?:forName|newInstance|getDeclared\w*|getMethod\w*|getField\w*|getConstructor\w*|isInstance|isAssignableFrom|getComponentType|isArray|getSuperclass|getInterfaces|getEnumConstants|getAnnotation\w*|isAnnotationPresent|getModifiers|getName|getSimpleName|cast|isEnum|isPrimitive)|reflect\/)/);
section("ServiceLoader", /^java\/util\/ServiceLoader\./);
section("Threads and executors", /^java\/(?:lang\/Thread\.|util\/concurrent\/\w+\.|lang\/Object\.(?:wait|notify\w*))/);
section("Files", /^java\/(?:io\/(?:File|FileInputStream|FileOutputStream|RandomAccessFile|FileReader|FileWriter)\.|nio\/file\/)/);
section("Networking", /^java\/net\/(?!URI\b)/, "`java.net.URI`/`URL` used only to build paths are included.");
section("System.exit / Runtime", /^java\/lang\/(?:System\.exit|Runtime\.)/);
section("System properties and environment", /^java\/lang\/System\.(?:getProperty|getenv|setProperty|getProperties)/);

const sync = new Map<string, [number, number]>();
for (const cf of classes.values()) {
  const g = group(cf.name);
  const cur = sync.get(g) ?? [0, 0];
  for (const m of cf.methods) {
    if (m.access & ACC_SYNCHRONIZED) cur[0]++;
    if (m.code) forEachInstruction(m.code.code, (op) => { if (op === 0xc2) cur[1]++; });
  }
  if (cur[0] || cur[1]) sync.set(g, cur);
}
line("### synchronized");
line();
table(["Package group", "synchronized methods", "monitorenter sites"], [...sync].sort((a, b) => b[1][0] + b[1][1] - a[1][0] - a[1][1]).map(([g, [a, b]]) => [`\`${g}\``, a, b]));

// opcodes used
const ops = new Map<number, number>();
for (const cf of classes.values()) for (const m of cf.methods) if (m.code) forEachInstruction(m.code.code, (op) => inc(ops, op));
line("### Opcodes never used by the jar");
line();
const { OPCODE_NAMES } = await import("../src/jvm/opcodes.ts");
line(OPCODE_NAMES.filter((_, i) => !ops.has(i)).map((n) => `\`${n}\``).join(", ") || "None.");
line();

line("### Game-reachable classes outside the replaced backend that touch LWJGL directly");
line();
const lwjglUsers = [...reachGame].filter((n) => classes.has(n) && !BACKEND.test(n) && [...refsOf(classes.get(n)!)].some((r) => r.startsWith("org/lwjgl/") || r.startsWith("com/badlogic/gdx/backends/lwjgl3/")));
for (const n of lwjglUsers.sort()) {
  const refs = [...refsOf(classes.get(n)!)].filter((r) => r.startsWith("org/lwjgl/") || r.startsWith("com/badlogic/gdx/backends/lwjgl3/"));
  line(`- \`${n.replaceAll("/", ".")}\`: ${refs.map((r) => `\`${r.replaceAll("/", ".")}\``).join(", ")}`);
}
line();

writeFileSync(outPath, out.join("\n"));
console.log(`wrote ${outPath}: ${out.length} lines`);
